    public ListedCompanyFinancialProfile require(String stockKey) {
        return profiles.stream()
                .filter(profile -> profile.stockKey().equals(stockKey))
                .findFirst()
                .orElseThrow();
    }

    /** NPC 재무 시뮬레이션이 직접 관리하는 고정 종목인지 확인한다. */
    public boolean supports(String stockKey) {
        return profiles.stream().anyMatch(profile -> profile.stockKey().equals(stockKey));
    }

